"""
Autonomous Security Auditor Agent
Scans target repositories for hardcoded secrets, insecure patterns, and dependency vulnerabilities.
Governing Authority: Governing Officer Tarwater
"""

import os
import re
import base64
import logging
import requests

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s"
)

GITHUB_API_URL = "https://api.github.com"

# Common regex signatures for leaked tokens/secrets
SECRET_PATTERNS = [
    re.compile(r"ghp_[a-zA-Z0-9]{36}"),                 # GitHub Personal Access Token
    re.compile(r"sk-[a-zA-Z0-9]{48}"),                 # OpenAI API Key
    re.compile(r"AIzaSy[a-zA-Z0-9_-]{33}"),            # Google Gemini/Cloud API Key
    re.compile(r"bearer\s+[a-zA-Z0-9_\-\.]{20,}", re.I), # Generic Bearer Tokens
    re.compile(r"password\s*=\s*['\"].*?['\"]", re.I)    # Hardcoded passwords
]


def get_github_headers() -> dict:
    token = os.getenv("GH_PAT") or os.getenv("GITHUB_TOKEN")
    if not token:
        raise EnvironmentError("Missing GH_PAT or GITHUB_TOKEN environment variable.")
    return {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28"
    }


def scan_repo_contents(owner: str, repo: str) -> list[dict]:
    """Recursively fetches Python and configuration files from the target repository."""
    headers = get_github_headers()
    url = f"{GITHUB_API_URL}/repos/{owner}/{repo}/git/trees/main?recursive=1"
    
    resp = requests.get(url, headers=headers, timeout=15)
    if resp.status_code != 200:
        # Try master branch if main fails
        url = f"{GITHUB_API_URL}/repos/{owner}/{repo}/git/trees/master?recursive=1"
        resp = requests.get(url, headers=headers, timeout=15)
    
    if resp.status_code != 200:
        logging.error(f"Failed to fetch repository tree for {owner}/{repo}: {resp.text}")
        return []

    tree = resp.json().get("tree", [])
    files_to_inspect = []
    
    for item in tree:
        path = item.get("path", "")
        # Inspect python files, requirements, and configs, ignoring hidden/venv directories
        if item.get("type") == "blob" and not any(p.startswith(".") or p in ("venv", "__pycache__") for p in path.split("/")):
            if path.endswith((".py", ".yaml", ".yml", ".txt", ".json")):
                files_to_inspect.append(path)
                
    return files_to_inspect


def inspect_file_for_secrets(owner: str, repo: str, file_path: str) -> list[str]:
    """Downloads a file and scans its contents against secret regex signatures."""
    headers = get_github_headers()
    url = f"{GITHUB_API_URL}/repos/{owner}/{repo}/contents/{file_path}"
    resp = requests.get(url, headers=headers, timeout=15)
    
    if resp.status_code != 200:
        return []

    file_data = resp.json()
    if "content" not in file_data:
        return []

    content = base64.b64decode(file_data["content"]).decode("utf-8", errors="ignore")
    violations = []

    for idx, line in enumerate(content.splitlines(), start=1):
        # Skip commented out example keys
        if line.strip().startswith(("#", "//")) and "example" in line.lower():
            continue
        for pattern in SECRET_PATTERNS:
            if pattern.search(line):
                violations.append(f"Line {idx}: Potential hardcoded secret detected matching signature pattern.")
                break

    return violations


def open_security_issue_and_pr(owner: str, repo: str, findings: dict, policy: dict) -> None:
    """Opens a GitHub Security Incident Issue under Governing Officer Tarwater's mandate."""
    headers = get_github_headers()
    approver = policy.get("operational_mandate", {}).get("require_final_approval_from", "Tarwater")

    issue_body = (
        f"### 🛡️ Autonomous Security Auditor Incident Report\n\n"
        f"The Security Auditor Agent scanned target repository `{owner}/{repo}` and identified potential vulnerabilities:\n\n"
    )
    for file_path, issues in findings.items():
        issue_body += f"- **`{file_path}`**:\n"
        for issue in issues:
            issue_body += f"  - {issue}\n"

    issue_body += (
        f"\n*Governing Executive Sign-Off Required:* Governing Officer {approver}\n"
        f"*Action Taken:* Automated security alert generated by `autonomous-agent-swarm`."
    )

    issue_payload = {
        "title": f"[SECURITY ALERT] Vulnerability detected in {repo}",
        "body": issue_body,
        "labels": ["security", "automated-audit"]
    }

    issue_resp = requests.post(f"{GITHUB_API_URL}/repos/{owner}/{repo}/issues", headers=headers, json=issue_payload, timeout=30)
    if issue_resp.status_code == 201:
        logging.info(f"Successfully opened Security Issue on {owner}/{repo}: {issue_resp.json().get('html_url')}")
    else:
        logging.error(f"Failed to open security issue: {issue_resp.text}")


def run_security_audit(target_repo: str, policy: dict) -> None:
    """Orchestrates the full security scan across the target repository."""
    logging.info(f"Starting Security Auditor Agent on target: {target_repo}")
    owner, repo = target_repo.split("/", 1)
    
    files = scan_repo_contents(owner, repo)
    findings = {}

    for file_path in files:
        violations = inspect_file_for_secrets(owner, repo, file_path)
        if violations:
            findings[file_path] = violations

    if findings:
        logging.warning(f"Security vulnerabilities detected in {len(findings)} files across {target_repo}!")
        open_security_issue_and_pr(owner, repo, findings, policy)
    else:
        logging.info(f"Security audit complete for {target_repo}. No secret leaks or policy violations found.")


